def find_root(start):
    """Walk up from `start` to the directory holding .productflow/config.json."""
    current = Path(start).resolve()
    if current.is_file():
        current = current.parent
    for candidate in [current] + list(current.parents):
        if (candidate / CONFIG_DIR / CONFIG_NAME).is_file():
            return candidate
    raise PfError(7, "not initialized: no %s/%s found from %s upwards" % (CONFIG_DIR, CONFIG_NAME, current))


def load_config(root):
    """Read .productflow/config.json and fill in schema defaults."""
    path = Path(root) / CONFIG_DIR / CONFIG_NAME
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise PfError(7, "not initialized: missing %s" % path)
    except ValueError as exc:
        raise PfError(2, "invalid config JSON in %s: %s" % (path, exc))
    if not isinstance(raw, dict):
        raise PfError(2, "invalid config in %s: expected a JSON object" % path)
    config = dict(DEFAULT_CONFIG)
    config.update({k: v for k, v in raw.items() if v is not None})
    if config["prd_locale"] not in LABELS:
        sys.stderr.write(
            "warn: unknown prd_locale %r; using 'en' labels\n" % config["prd_locale"]
        )
        config["label_locale"] = "en"
    else:
        config["label_locale"] = config["prd_locale"]
    return config


