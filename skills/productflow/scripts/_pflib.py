def id_from_path(root, config, path):
    """docs/product/billing/invoicing/PRD.md -> product.billing.invoicing"""
    resolved = Path(path).resolve()
    base = docs_root(root, config).resolve()
    try:
        relative = resolved.relative_to(base)
    except ValueError:
        raise PfError(2, "%s is not inside %s" % (path, config["docs_root"]))
    if relative.name != "PRD.md":
        raise PfError(2, "%s is not a PRD.md file" % path)
    segments = list(relative.parts[:-1])
    return ".".join(["product"] + segments)


def path_from_id(root, config, doc_id):
    """product.billing.invoicing -> <root>/docs/product/billing/invoicing/PRD.md"""
    if not RE_PRD_ID.match(doc_id):
        raise PfError(2, "invalid document id: %s" % doc_id)
    segments = doc_id.split(".")[1:]
    return docs_root(root, config).joinpath(*segments) / "PRD.md"


def iter_prd_files(root, config):
    base = docs_root(root, config)
    if not base.is_dir():
        return []
    return sorted(p for p in base.rglob("PRD.md") if p.is_file())


def iter_change_dirs(root, config, include_archive=True):
    base = changes_root(root, config)
    if not base.is_dir():
        return [], []
    active = sorted(
        p for p in base.iterdir() if p.is_dir() and p.name != "archive"
    )
    archived = []
    if include_archive and (base / "archive").is_dir():
        archived = sorted(p for p in (base / "archive").iterdir() if p.is_dir())
    return active, archived


def domain_prefix(domain):
    """billing -> BILLING; identity/user-auth -> IDENTITY"""
    first = str(domain).strip().strip("/").split("/")[0]
    if not first:
        raise PfError(2, "empty domain")
    upper = first.upper()
    return re.sub(r"[^A-Z0-9-]", "-", upper)


def next_req_ids(root, config, domain, count=1):
    """Allocate the next N requirement IDs for a domain, scanning all sources."""
    if count < 1:
        raise PfError(2, "count must be >= 1")
    prefix = domain_prefix(domain)
    pattern = re.compile(r"\bREQ-%s-(\d{3})\b" % re.escape(prefix))
    highest = 0
    for path in iter_prd_files(root, config):
        for match in pattern.finditer(_read(path)):
            highest = max(highest, int(match.group(1)))
    active, archived = iter_change_dirs(root, config)
    for folder in active + archived:
        delta = folder / "requirements.md"
        if delta.is_file():
            for match in pattern.finditer(_read(delta)):
                highest = max(highest, int(match.group(1)))
    return ["REQ-%s-%03d" % (prefix, highest + i) for i in range(1, count + 1)]


