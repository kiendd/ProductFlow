class PfError(Exception):
    """Error carrying the process exit code the CLI should return."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


def main_wrapper(fn):
    """Wrap a main(argv) -> int function so PfError maps to an exit code."""

    def wrapped(argv=None):
        if argv is None:
            argv = sys.argv[1:]
        try:
            result = fn(argv)
            return 0 if result is None else int(result)
        except PfError as exc:
            sys.stderr.write("error: %s\n" % exc.message)
            return exc.code
        except BrokenPipeError:  # pragma: no cover - defensive
            return 0

    return wrapped


def emit(payload):
    """Print a one-line JSON summary on stdout."""
    sys.stdout.write(json.dumps(payload, ensure_ascii=False, sort_keys=True) + "\n")


