def templates_dir():
    return Path(__file__).resolve().parent.parent / "assets" / "templates"


def render_template(name, mapping):
    """Load a template, substitute {{KEY}} tokens, drop empty frontmatter keys."""
    path = templates_dir() / name
    if not path.is_file():
        raise PfError(2, "missing template: %s" % path)
    text = path.read_text(encoding="utf-8")
    for key, value in mapping.items():
        text = text.replace("{{%s}}" % key, "" if value is None else str(value))
    return _drop_empty_frontmatter_lines(text)


def _drop_empty_frontmatter_lines(text):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return text
    end = None
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            end = idx
            break
    if end is None:
        return text
    kept = [lines[0]]
    for line in lines[1:end]:
        match = RE_FM_LINE.match(line)
        if match and not match.group(2).strip():
            continue
        kept.append(line)
    kept.extend(lines[end:])
    return "\n".join(kept)


def write_text(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    path.write_text(text, encoding="utf-8")
    return path


