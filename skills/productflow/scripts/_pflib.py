def unmerged_delta_ids(root, config, delta):
    """Return (missing, lingering) requirement IDs blocking an archive."""
    manifest = build_manifest(root, config)
    known = manifest_req_ids(manifest)
    missing = [r["id"] for r in delta["added"] + delta["modified"] if r["id"] and r["id"] not in known]
    lingering = [r["id"] for r in delta["removed"] if r["id"] and r["id"] in known]
    return sorted(set(missing)), sorted(set(lingering))


def move_tree(src, dest):
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dest))
    return dest


def ensure_gitignore(root):
    """Make sure .productflow/runs/ is ignored; return True if the file changed."""
    path = Path(root) / ".gitignore"
    entry = ".productflow/runs/"
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        if any(line.strip() == entry for line in text.split("\n")):
            return False
        if text and not text.endswith("\n"):
            text += "\n"
        path.write_text(text + entry + "\n", encoding="utf-8")
        return True
    path.write_text(entry + "\n", encoding="utf-8")
    return True


