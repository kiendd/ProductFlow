def _split_sections(body_lines, offset):
    """Return (order, sections) where sections maps H2 title -> line list."""
    order = []
    sections = {}
    current = None
    for idx, line in enumerate(body_lines):
        match = RE_H2.match(line)
        if match:
            current = match.group(1).strip()
            order.append(current)
            sections.setdefault(current, [])
            continue
        if current is not None:
            sections[current].append((offset + idx, line))
    return order, sections


def _read(path):
    return Path(path).read_text(encoding="utf-8")


def _requirement_blocks(lines):
    """Split `lines` (list of (lineno, text)) into blocks per ### heading."""
    blocks = []
    current = None
    for lineno, text in lines:
        match = RE_REQ_HEADING.match(text)
        if match:
            current = {
                "id": match.group(1),
                "title": match.group(2).strip(),
                "line": lineno,
                "lines": [],
            }
            blocks.append(current)
            continue
        if text.startswith("### "):
            # A ### heading that is not a valid requirement heading.
            current = {
                "id": None,
                "title": text[4:].strip(),
                "line": lineno,
                "lines": [],
                "malformed": True,
            }
            blocks.append(current)
            continue
        if current is not None:
            current["lines"].append((lineno, text))
    return blocks


def _field_line(lines, name):
    pattern = re.compile(r"^\*\*%s\*\*:\s*(.*)$" % re.escape(name))
    for _, text in lines:
        match = pattern.match(text)
        if match:
            return match.group(1).strip()
    return None


def _scenarios(lines):
    """Extract scenarios from a requirement block."""
    out = []
    current = None
    for lineno, text in lines:
        match = RE_SCENARIO.match(text)
        if match:
            current = {
                "name": match.group(1).strip(),
                "line": lineno,
                "has_when": False,
                "has_then": False,
            }
            out.append(current)
            continue
        if text.startswith("#### "):
            current = None
            continue
        if current is not None and text.lstrip().startswith("-"):
            if "**WHEN**" in text:
                current["has_when"] = True
            if "**THEN**" in text:
                current["has_then"] = True
    return out


def parse_prd(path):
    """Parse a PRD document into fields, sections, and requirements."""
    path = Path(path)
    text = _read(path)
    fields, body, fm_errors = parse_frontmatter(text)
    total_lines = text.split("\n")
    offset = len(total_lines) - len(body.split("\n")) + 1
    body_lines = body.split("\n")
    order, sections = _split_sections(body_lines, offset)
    requirements = []
    for block in _requirement_blocks(sections.get("Requirements", [])):
        scen = _scenarios(block["lines"])
        requirements.append(
            {
                "id": block["id"],
                "title": block["title"],
                "line": block["line"],
                "status": _field_line(block["lines"], "Status"),
                "statement": _field_line(block["lines"], "Statement"),
                "scenarios": [s["name"] for s in scen],
                "scenario_details": scen,
                "malformed": block.get("malformed", False),
            }
        )
    return {
        "path": path,
        "fields": fields,
        "fm_errors": fm_errors,
        "body": body,
        "section_order": order,
        "sections": {k: "\n".join(t for _, t in v) for k, v in sections.items()},
        "section_lines": sections,
        "requirements": requirements,
        "text": text,
    }


def parse_delta(path):
    """Parse a change's requirements.md into its four delta buckets."""
    path = Path(path)
    text = _read(path)
    fields, body, fm_errors = parse_frontmatter(text)
    total_lines = text.split("\n")
    offset = len(total_lines) - len(body.split("\n")) + 1
    order, sections = _split_sections(body.split("\n"), offset)
    result = {
        "path": path,
        "fields": fields,
        "fm_errors": fm_errors,
        "section_order": order,
        "added": [],
        "modified": [],
        "removed": [],
        "renamed": [],
        "text": text,
    }
    bucket_for = {
        "ADDED Requirements": "added",
        "MODIFIED Requirements": "modified",
        "REMOVED Requirements": "removed",
        "RENAMED Requirements": "renamed",
    }
    for heading, key in bucket_for.items():
        for block in _requirement_blocks(sections.get(heading, [])):
            scen = _scenarios(block["lines"])
            result[key].append(
                {
                    "id": block["id"],
                    "title": block["title"],
                    "line": block["line"],
                    "target": _field_line(block["lines"], "Target"),
                    "status": _field_line(block["lines"], "Status"),
                    "statement": _field_line(block["lines"], "Statement"),
                    "reason": _field_line(block["lines"], "Reason"),
                    "migration": _field_line(block["lines"], "Migration"),
                    "from": _field_line(block["lines"], "FROM"),
                    "to": _field_line(block["lines"], "TO"),
                    "scenarios": [s["name"] for s in scen],
                    "scenario_details": scen,
                    "malformed": block.get("malformed", False),
                    "block": render_block(block),
                }
            )
    return result


def render_block(block):
    """Reassemble a requirement block (heading + body) as markdown text."""
    head = "### %s: %s" % (block["id"], block["title"]) if block["id"] else "### %s" % block["title"]
    lines = [head] + [text for _, text in block["lines"]]
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines) + "\n"


def parse_tasks(path):
    """Parse tasks.md into checkbox items with their four required parts."""
    path = Path(path)
    text = _read(path)
    fields, body, fm_errors = parse_frontmatter(text)
    total_lines = text.split("\n")
    offset = len(total_lines) - len(body.split("\n")) + 1
    lines = body.split("\n")
    items = []
    current = None
    for idx, line in enumerate(lines):
        lineno = offset + idx
        match = RE_TASK.match(line)
        if match:
            raw = match.group(3)
            verify = None
            title = raw
            if " — verify: " in raw:
                title, verify = raw.split(" — verify: ", 1)
            current = {
                "num": match.group(2),
                "text": title.strip(),
                "raw": raw,
                "done": match.group(1) == "x",
                "verify": verify.strip() if verify else None,
                "requirements": [],
                "files": None,
                "steps": None,
                "line": lineno,
            }
            items.append(current)
            continue
        if current is None:
            continue
        stripped = line.strip()
        if stripped.startswith("- Requirements:"):
            value = stripped[len("- Requirements:") :].strip()
            current["requirements"] = [p.strip() for p in value.split(",") if p.strip()]
        elif stripped.startswith("- Files:"):
            current["files"] = stripped[len("- Files:") :].strip()
        elif stripped.startswith("- Steps:"):
            current["steps"] = stripped[len("- Steps:") :].strip()
        elif not stripped:
            continue
        elif not stripped.startswith("-") and not stripped.startswith("#"):
            continue
        elif stripped.startswith("#"):
            current = None
    return {
        "path": path,
        "fields": fields,
        "fm_errors": fm_errors,
        "total": len(items),
        "done": sum(1 for i in items if i["done"]),
        "items": items,
        "text": text,
    }


