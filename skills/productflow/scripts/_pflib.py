def build_manifest(root, config):
    """Build the machine-readable map of the docs tree and change folders."""
    documents = []
    for path in iter_prd_files(root, config):
        doc = parse_prd(path)
        fields = doc["fields"]
        requirements = []
        for req in doc["requirements"]:
            if not req["id"]:
                continue
            requirements.append(
                {
                    "id": req["id"],
                    "title": req["title"],
                    "status": req["status"] or "",
                    "scenarios": len(req["scenarios"]),
                }
            )
        requirements.sort(key=lambda r: r["id"])
        implements = fields.get("implements", [])
        if not isinstance(implements, list):
            implements = [implements] if implements else []
        documents.append(
            {
                "id": fields.get("id", ""),
                "path": rel(root, path),
                "type": fields.get("type", ""),
                "domain": fields.get("domain", ""),
                "parent": fields.get("parent") or None,
                "status": fields.get("status", ""),
                "title": fields.get("title", ""),
                "updated": fields.get("updated", ""),
                "implements": implements,
                "requirements": requirements,
            }
        )
    documents.sort(key=lambda d: d["id"])

    active_dirs, archived_dirs = iter_change_dirs(root, config)
    active = []
    for folder in active_dirs:
        change_file = folder / "change.md"
        if not change_file.is_file():
            continue
        fields, _, _ = parse_frontmatter(_read(change_file))
        tasks_file = folder / "tasks.md"
        total = done = 0
        if tasks_file.is_file():
            tasks = parse_tasks(tasks_file)
            total, done = tasks["total"], tasks["done"]
        domains = fields.get("domains", [])
        if not isinstance(domains, list):
            domains = [domains] if domains else []
        active.append(
            {
                "slug": fields.get("id", folder.name),
                "title": fields.get("title", ""),
                "status": fields.get("status", ""),
                "tasks_total": total,
                "tasks_done": done,
                "domains": domains,
            }
        )
    active.sort(key=lambda c: c["slug"])

    archived = []
    for folder in archived_dirs:
        match = RE_ARCHIVE_DIR.match(folder.name)
        if match:
            archived_on, slug = match.group(1), match.group(2)
        else:
            archived_on, slug = "", folder.name
        archived.append(
            {"slug": slug, "archived": archived_on, "path": rel(root, folder)}
        )
    archived.sort(key=lambda c: (c["archived"], c["slug"]))

    return {
        "generated": today(),
        "version": 1,
        "locale": config["prd_locale"],
        "documents": documents,
        "changes": {"active": active, "archived": archived},
    }


def dump_manifest(manifest):
    return json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"


def render_index(manifest, locale):
    """Render docs/product/index.md from a manifest."""
    labels = LABELS.get(locale, LABELS["en"])
    out = [INDEX_HEADER, "", "# %s" % labels["index_title"], ""]
    out.append("%s: %s" % (labels["generated"], manifest["generated"]))
    out.append("")
    out.append("## %s" % labels["documents"])
    out.append("")
    out.append(
        "| %s | %s | %s | %s | %s | %s |"
        % (
            labels["id"],
            labels["title"],
            labels["type"],
            labels["status"],
            labels["requirements"],
            labels["path"],
        )
    )
    out.append("|---|---|---|---|---|---|")
    if manifest["documents"]:
        for doc in manifest["documents"]:
            out.append(
                "| `%s` | %s | %s | %s | %d | `%s` |"
                % (
                    doc["id"],
                    doc["title"],
                    doc["type"],
                    doc["status"],
                    len(doc["requirements"]),
                    doc["path"],
                )
            )
    else:
        out.append("| — | %s | — | — | 0 | — |" % labels["none"])
    out.append("")
    out.append("## %s" % labels["active_changes"])
    out.append("")
    active = manifest["changes"]["active"]
    if active:
        out.append(
            "| %s | %s | %s | %s | %s |"
            % (labels["slug"], labels["title"], labels["status"], labels["tasks"], labels["domains"])
        )
        out.append("|---|---|---|---|---|")
        for change in active:
            out.append(
                "| `%s` | %s | %s | %d/%d | %s |"
                % (
                    change["slug"],
                    change["title"],
                    change["status"],
                    change["tasks_done"],
                    change["tasks_total"],
                    ", ".join(change["domains"]),
                )
            )
    else:
        out.append(labels["none"])
    out.append("")
    out.append("## %s" % labels["archived_changes"])
    out.append("")
    archived = manifest["changes"]["archived"]
    if archived:
        out.append("| %s | %s | %s |" % (labels["slug"], labels["archived_on"], labels["path"]))
        out.append("|---|---|---|")
        for change in archived:
            out.append(
                "| `%s` | %s | `%s` |" % (change["slug"], change["archived"], change["path"])
            )
    else:
        out.append(labels["none"])
    out.append("")
    return "\n".join(out)


def write_index(root, config):
    """Regenerate index.md and manifest.json; return the manifest."""
    manifest = build_manifest(root, config)
    base = docs_root(root, config)
    base.mkdir(parents=True, exist_ok=True)
    write_text(base / "manifest.json", dump_manifest(manifest))
    write_text(base / "index.md", render_index(manifest, config["label_locale"]))
    return manifest


def load_manifest(root, config):
    path = docs_root(root, config) / "manifest.json"
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return None


def manifest_req_ids(manifest):
    ids = set()
    for doc in manifest.get("documents", []):
        for req in doc.get("requirements", []):
            ids.add(req["id"])
    return ids


