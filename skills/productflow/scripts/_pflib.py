def finding(level, code, path, line, message):
    return {
        "level": level,
        "code": code,
        "path": str(path),
        "line": line,
        "message": message,
    }


def validate(root, config):
    """Run every structural rule over the docs and change trees."""
    root = Path(root)
    findings = []
    seen_req = {}

    for path in iter_prd_files(root, config):
        findings.extend(_validate_prd(root, config, path, seen_req))

    active_dirs, archived_dirs = iter_change_dirs(root, config)
    for folder in active_dirs + archived_dirs:
        change_file = folder / "change.md"
        if change_file.is_file():
            findings.extend(_validate_change(root, change_file))
        delta_file = folder / "requirements.md"
        if delta_file.is_file():
            findings.extend(_validate_delta(root, delta_file))
        tasks_file = folder / "tasks.md"
        if tasks_file.is_file():
            findings.extend(_validate_tasks(root, tasks_file))

    findings.extend(_validate_manifest(root, config))

    findings.sort(key=lambda f: (f["path"], f["line"] or 0, f["code"]))
    return findings


def _validate_links(root, path, text):
    out = []
    base = Path(path).parent
    for idx, line in enumerate(text.split("\n"), start=1):
        for match in RE_LINK.finditer(line):
            target = match.group(1)
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            target = target.split("#", 1)[0]
            if not target:
                continue
            if not (base / target).exists():
                out.append(
                    finding(
                        "error",
                        "link-broken",
                        rel(root, path),
                        idx,
                        "link target does not exist: %s" % target,
                    )
                )
    return out


def _validate_prd(root, config, path, seen_req):
    out = []
    rpath = rel(root, path)
    doc = parse_prd(path)
    for err in doc["fm_errors"]:
        out.append(finding("error", "frontmatter-syntax", rpath, 1, err))
    fields = doc["fields"]

    for key in REQUIRED_PRD_KEYS:
        if key not in fields or fields[key] in ("", []):
            out.append(
                finding("error", "frontmatter-missing-key", rpath, 1, "missing key: %s" % key)
            )

    if fields.get("type") and fields["type"] not in PRD_TYPES:
        out.append(
            finding(
                "error",
                "frontmatter-bad-value",
                rpath,
                1,
                "type must be one of %s" % "|".join(sorted(PRD_TYPES)),
            )
        )
    if fields.get("status") and fields["status"] not in PRD_STATUSES:
        out.append(
            finding(
                "error",
                "frontmatter-bad-value",
                rpath,
                1,
                "status must be one of %s" % "|".join(sorted(PRD_STATUSES)),
            )
        )
    if fields.get("updated") and not RE_DATE.match(str(fields["updated"])):
        out.append(
            finding("error", "frontmatter-bad-value", rpath, 1, "updated must be YYYY-MM-DD")
        )
    doc_id = fields.get("id")
    if doc_id:
        if not RE_PRD_ID.match(str(doc_id)):
            out.append(
                finding(
                    "error",
                    "frontmatter-bad-value",
                    rpath,
                    1,
                    "id must match ^product(\\.[a-z0-9-]+)*$",
                )
            )
        else:
            expected = id_from_path(root, config, path)
            if doc_id != expected:
                out.append(
                    finding(
                        "error",
                        "id-path-mismatch",
                        rpath,
                        1,
                        "id %s does not match path (expected %s)" % (doc_id, expected),
                    )
                )

    present = [h for h in doc["section_order"] if h in PRD_SECTIONS]
    for name in PRD_SECTIONS:
        if name not in present:
            out.append(
                finding("error", "section-missing", rpath, 1, "missing section: ## %s" % name)
            )
    expected_order = [h for h in PRD_SECTIONS if h in present]
    if present != expected_order:
        out.append(
            finding(
                "error",
                "section-order",
                rpath,
                1,
                "sections must appear in this order: %s" % ", ".join(PRD_SECTIONS),
            )
        )

    for req in doc["requirements"]:
        out.extend(_validate_requirement(rpath, req, require_target=False))
        if req["id"]:
            key = req["id"]
            if key in seen_req:
                out.append(
                    finding(
                        "error",
                        "req-duplicate",
                        rpath,
                        req["line"],
                        "%s already defined in %s" % (key, seen_req[key]),
                    )
                )
            else:
                seen_req[key] = rpath

    out.extend(_validate_links(root, path, doc["text"]))
    return out


def _validate_requirement(rpath, req, require_target):
    out = []
    if req.get("malformed") or not req["id"]:
        out.append(
            finding(
                "error",
                "req-format",
                rpath,
                req["line"],
                "requirement heading must match '### REQ-<PREFIX>-<NNN>: <title>'",
            )
        )
        return out
    if not req.get("status"):
        out.append(
            finding("error", "req-format", rpath, req["line"], "%s: missing **Status**:" % req["id"])
        )
    if not req.get("statement"):
        out.append(
            finding(
                "error", "req-format", rpath, req["line"], "%s: missing **Statement**:" % req["id"]
            )
        )
    if require_target and not req.get("target"):
        out.append(
            finding(
                "error",
                "delta-missing-target",
                rpath,
                req["line"],
                "%s: missing **Target**: (id of the destination PRD)" % req["id"],
            )
        )
    if not req["scenario_details"]:
        out.append(
            finding(
                "error",
                "req-no-scenario",
                rpath,
                req["line"],
                "%s: needs at least one '#### Scenario: <name>'" % req["id"],
            )
        )
    for scenario in req["scenario_details"]:
        if not scenario["has_when"] or not scenario["has_then"]:
            out.append(
                finding(
                    "error",
                    "scenario-no-when-then",
                    rpath,
                    scenario["line"],
                    "%s / %s: needs a **WHEN** bullet and a **THEN** bullet"
                    % (req["id"], scenario["name"]),
                )
            )
    return out


def _validate_change(root, path):
    out = []
    rpath = rel(root, path)
    text = _read(path)
    fields, _, errors = parse_frontmatter(text)
    for err in errors:
        out.append(finding("error", "frontmatter-syntax", rpath, 1, err))
    for key in ("id", "title", "status"):
        if key not in fields or fields[key] in ("", []):
            out.append(
                finding("error", "frontmatter-missing-key", rpath, 1, "missing key: %s" % key)
            )
    if fields.get("status") and fields["status"] not in CHANGE_STATUSES:
        out.append(
            finding(
                "error",
                "frontmatter-bad-value",
                rpath,
                1,
                "status must be one of %s" % "|".join(sorted(CHANGE_STATUSES)),
            )
        )
    if fields.get("classification") and fields["classification"] not in CHANGE_CLASSIFICATIONS:
        out.append(
            finding(
                "error",
                "frontmatter-bad-value",
                rpath,
                1,
                "classification must be one of %s" % "|".join(sorted(CHANGE_CLASSIFICATIONS)),
            )
        )
    out.extend(_validate_links(root, path, text))
    return out


def _validate_delta(root, path):
    out = []
    rpath = rel(root, path)
    delta = parse_delta(path)
    for err in delta["fm_errors"]:
        out.append(finding("error", "frontmatter-syntax", rpath, 1, err))
    if "change" not in delta["fields"]:
        out.append(finding("error", "frontmatter-missing-key", rpath, 1, "missing key: change"))
    present = [h for h in delta["section_order"] if h in DELTA_SECTIONS]
    for name in DELTA_SECTIONS:
        if name not in present:
            out.append(
                finding("error", "section-missing", rpath, 1, "missing section: ## %s" % name)
            )

    for req in delta["added"]:
        out.extend(_validate_requirement(rpath, req, require_target=True))
    for req in delta["modified"]:
        out.extend(_validate_requirement(rpath, req, require_target=True))
        if req["id"] and (not req.get("statement") or not req["scenario_details"]):
            out.append(
                finding(
                    "error",
                    "delta-modified-incomplete",
                    rpath,
                    req["line"],
                    "%s: MODIFIED must restate the full requirement (statement + every scenario)"
                    % req["id"],
                )
            )
    for req in delta["removed"]:
        if not req["id"]:
            out.append(
                finding(
                    "error",
                    "req-format",
                    rpath,
                    req["line"],
                    "REMOVED heading must match '### REQ-<PREFIX>-<NNN>: <title>'",
                )
            )
            continue
        if not req.get("reason") or not req.get("migration"):
            out.append(
                finding(
                    "error",
                    "delta-removed-no-reason",
                    rpath,
                    req["line"],
                    "%s: REMOVED needs **Reason**: and **Migration**:" % req["id"],
                )
            )
    for req in delta["renamed"]:
        if not req["id"]:
            out.append(
                finding(
                    "error",
                    "req-format",
                    rpath,
                    req["line"],
                    "RENAMED heading must match '### REQ-<PREFIX>-<NNN>: <title>'",
                )
            )
            continue
        if not req.get("from") or not req.get("to"):
            out.append(
                finding(
                    "error",
                    "req-format",
                    rpath,
                    req["line"],
                    "%s: RENAMED needs **FROM**: and **TO**:" % req["id"],
                )
            )
    out.extend(_validate_links(root, path, delta["text"]))
    return out


def _validate_tasks(root, path):
    out = []
    rpath = rel(root, path)
    tasks = parse_tasks(path)
    for err in tasks["fm_errors"]:
        out.append(finding("error", "frontmatter-syntax", rpath, 1, err))
    if "change" not in tasks["fields"]:
        out.append(finding("error", "frontmatter-missing-key", rpath, 1, "missing key: change"))
    for line_no, line in enumerate(tasks["text"].split("\n"), start=1):
        stripped = line.strip()
        if stripped.startswith("- [") and not RE_TASK.match(line):
            out.append(
                finding(
                    "error",
                    "task-format",
                    rpath,
                    line_no,
                    "checkbox must match '- [ ] <n>.<m> <text>'",
                )
            )
    for item in tasks["items"]:
        missing = []
        if not item["verify"]:
            missing.append("' — verify: <command>'")
        if not item["requirements"]:
            missing.append("'- Requirements:'")
        if not item["files"]:
            missing.append("'- Files:'")
        if not item["steps"]:
            missing.append("'- Steps:'")
        if missing:
            out.append(
                finding(
                    "error",
                    "task-format",
                    rpath,
                    item["line"],
                    "task %s is missing %s" % (item["num"], ", ".join(missing)),
                )
            )
    out.extend(_validate_links(root, path, tasks["text"]))
    return out


def _validate_manifest(root, config):
    out = []
    base = docs_root(root, config)
    if not base.is_dir():
        return out
    rpath = rel(root, base / "manifest.json")
    stored = load_manifest(root, config)
    if stored is None:
        return [
            finding(
                "error", "manifest-stale", rpath, 1, "manifest.json missing or unreadable; run pf-index"
            )
        ]
    fresh = build_manifest(root, config)
    stored_cmp = dict(stored)
    fresh_cmp = dict(fresh)
    stored_cmp.pop("generated", None)
    fresh_cmp.pop("generated", None)
    if json.dumps(stored_cmp, sort_keys=True, ensure_ascii=False) != json.dumps(
        fresh_cmp, sort_keys=True, ensure_ascii=False
    ):
        out.append(
            finding("error", "manifest-stale", rpath, 1, "manifest.json is out of date; run pf-index")
        )
    index_path = base / "index.md"
    if not index_path.is_file():
        out.append(
            finding(
                "error",
                "manifest-stale",
                rel(root, index_path),
                1,
                "index.md missing; run pf-index",
            )
        )
    return out


def filter_findings(findings, path_filter):
    if not path_filter:
        return findings
    prefix = str(Path(path_filter)).rstrip("/")
    return [f for f in findings if f["path"] == prefix or f["path"].startswith(prefix + "/")]


