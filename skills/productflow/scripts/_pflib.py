def parse_frontmatter(text):
    """Parse the strict frontmatter subset.

    Returns (fields, body, errors). `errors` holds human-readable grammar
    violations; callers turn them into `frontmatter-syntax` findings.
    """
    fields = {}
    errors = []
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text, ["missing frontmatter: file must start with '---'"]
    end = None
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            end = idx
            break
    if end is None:
        return {}, text, ["unterminated frontmatter: no closing '---'"]
    for idx in range(1, end):
        line = lines[idx]
        if not line.strip():
            errors.append("line %d: blank line inside frontmatter" % (idx + 1))
            continue
        match = RE_FM_LINE.match(line)
        if not match:
            errors.append("line %d: not a 'key: value' pair: %s" % (idx + 1, line.strip()))
            continue
        key, raw = match.group(1), match.group(2).strip()
        if key in fields:
            errors.append("line %d: duplicate key '%s'" % (idx + 1, key))
        fields[key] = _parse_value(raw)
    body = "\n".join(lines[end + 1 :])
    return fields, body, errors


def _parse_value(raw):
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        if not inner:
            return []
        return [part.strip() for part in inner.split(",") if part.strip()]
    return raw


def dump_frontmatter(fields):
    """Serialize fields in the fixed key order, skipping absent keys."""
    out = ["---"]
    seen = set()
    for key in FRONTMATTER_KEY_ORDER:
        if key not in fields:
            continue
        seen.add(key)
        out.append("%s: %s" % (key, _dump_value(fields[key])))
    for key in sorted(k for k in fields if k not in seen):
        out.append("%s: %s" % (key, _dump_value(fields[key])))
    out.append("---")
    return "\n".join(out) + "\n"


def _dump_value(value):
    if isinstance(value, list):
        return "[%s]" % ", ".join(str(v) for v in value)
    return str(value)


def replace_frontmatter(text, fields):
    """Return `text` with its frontmatter block replaced by `fields`."""
    _, body, _ = parse_frontmatter(text)
    return dump_frontmatter(fields) + body


